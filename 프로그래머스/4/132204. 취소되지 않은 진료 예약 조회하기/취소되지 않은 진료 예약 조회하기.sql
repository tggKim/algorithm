SELECT T1.APNT_NO, T2.PT_NAME, T2.PT_NO, T1.MCDP_CD, T3.DR_NAME, T1.APNT_YMD
FROM APPOINTMENT T1
INNER JOIN PATIENT T2
    ON T1.PT_NO = T2.PT_NO
INNER JOIN DOCTOR T3
    ON T1.MDDR_ID = T3.DR_ID
WHERE T1.MCDP_CD = 'CS' AND T1.APNT_YMD >= '2022-04-13' AND T1.APNT_YMD < '2022-04-14' AND T1.APNT_CNCL_YMD IS NULL
ORDER BY T1.APNT_YMD