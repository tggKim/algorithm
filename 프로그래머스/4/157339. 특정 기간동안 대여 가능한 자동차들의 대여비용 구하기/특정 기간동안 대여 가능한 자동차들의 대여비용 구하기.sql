SELECT T1.CAR_ID, T1.CAR_TYPE, T1.DAILY_FEE * (1 - (T3.DISCOUNT_RATE / 100)) * 30 AS FEE
FROM CAR_RENTAL_COMPANY_CAR T1
INNER JOIN CAR_RENTAL_COMPANY_DISCOUNT_PLAN T3
    ON T1.CAR_TYPE = T3.CAR_TYPE AND T3.DURATION_TYPE = '30일 이상'
WHERE T1.CAR_TYPE IN('세단', 'SUV') AND T1.DAILY_FEE * (1 - (T3.DISCOUNT_RATE / 100)) * 30 >= 500000 AND T1.DAILY_FEE * (1 - (T3.DISCOUNT_RATE / 100)) * 30 < 2000000
AND NOT EXISTS(
    SELECT 1
    FROM  CAR_RENTAL_COMPANY_RENTAL_HISTORY T2
    WHERE T1.CAR_ID = T2.CAR_ID AND ((T2.END_DATE BETWEEN '2022-11-01' AND '2022-11-30' OR T2.START_DATE BETWEEN '2022-11-01' AND '2022-11-30') OR (T2.START_DATE < '2022-11-01' AND T2.END_DATE > '2022-11-30'))
)
ORDER BY FEE DESC, T1.CAR_TYPE, T1.CAR_ID DESC